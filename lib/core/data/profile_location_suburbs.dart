  /// Suburbs for the selected country + city (empty if unknown).
  static List<String> forCity(String? country, String? city) {
    if (country == null || city == null) return const [];
    final byCity = byCountryAndCity[country.trim()];
    if (byCity == null) return const [];
    return byCity[city.trim()] ?? const [];
  }
